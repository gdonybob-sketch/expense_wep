// ======================================
// Apply Language
// ======================================

function applyLanguage(language) {

    const html =
        document.getElementById("html");

    if (!html) return;


    // ==================================
    // Check Language
    // ==================================

    if (!translations[language]) {

        language = "ar";

    }


    // ==================================
    // HTML Language & Direction
    // ==================================

    html.setAttribute(
        "lang",
        language
    );


    html.setAttribute(
        "dir",
        language === "ar"
            ? "rtl"
            : "ltr"
    );


    // ==================================
    // Translate Text
    // ==================================

    const elements =
        document.querySelectorAll(
            "[data-lang]"
        );


    elements.forEach(element => {

        const key =
            element.getAttribute(
                "data-lang"
            );


        if (
            translations[language][key]
            !== undefined
        ) {

            element.textContent =
                translations[language][key];

        }

    });


    // ==================================
    // Translate Placeholders
    // ==================================

    const placeholderElements =
        document.querySelectorAll(
            "[data-lang-placeholder]"
        );


    placeholderElements.forEach(element => {

        const key =
            element.getAttribute(
                "data-lang-placeholder"
            );


        if (
            translations[language][key]
            !== undefined
        ) {

            element.placeholder =
                translations[language][key];

        }

    });


    // ==================================
    // Save Language
    // ==================================

    AppStorage.saveLanguage(language);


    // ==================================
    // Update Button
    // ==================================

    updateLanguageButton(
        language
    );


    // ==================================
    // Notify Other Scripts
    // ==================================

    document.dispatchEvent(
        new CustomEvent("languageChanged", {
            detail: { language }
        })
    );

}


// ======================================
// Update Language Button
// ======================================

function updateLanguageButton(language) {

    const button =
        document.getElementById(
            "language-btn"
        );


    if (!button) return;


    if (language === "ar") {

        button.textContent =
            "🌐 EN";

    } else {

        button.textContent =
            "🌐 AR";

    }

}


// ======================================
// Toggle Language
// ======================================

function toggleLanguage() {

    const currentLanguage =
        AppStorage.getLanguage();


    const newLanguage =
        currentLanguage === "ar"
            ? "en"
            : "ar";


    applyLanguage(
        newLanguage
    );

}


// ======================================
// Start Language System
// ======================================

document.addEventListener(
    "DOMContentLoaded",
    () => {

        const savedLanguage =
            AppStorage.getLanguage();


        applyLanguage(
            savedLanguage
        );


        const languageBtn =
            document.getElementById(
                "language-btn"
            );


        if (languageBtn) {

            languageBtn.addEventListener(
                "click",
                toggleLanguage
            );

        }

    }
);