// ======================================
// Auth Guard (حماية من جهة العميل فقط)
// ======================================
// ⚠️ تنبيه مهم: هذا ليس نظام حماية حقيقي.
// لا يوجد خادم أو تحقق فعلي من الهوية —
// فقط علامة محفوظة في localStorage. أي شخص
// يفتح "أدوات المطوّر" في المتصفح يستطيع
// تجاوز هذا الفحص بسهولة تامة. هذا مناسب فقط
// كواجهة دخول بسيطة لتطبيق يعمل محليًا بالكامل،
// وليس كحماية فعلية للبيانات الحساسة.
// ======================================
// يجب تحميل هذا الملف قبل أي محتوى آخر في
// <head> (قبل حتى ملفات CSS) لتقليل "وميض"
// ظهور الصفحة المحمية قبل إعادة التوجيه.
// ======================================

(function () {

    try {

        const loggedIn =
            localStorage.getItem("isLoggedIn") === "1";

        if (!loggedIn) {

            const currentPage =
                location.pathname.split("/").pop() || "dashboard.html";

            location.replace(
                "login.html?redirect=" + encodeURIComponent(currentPage)
            );

        }

    } catch (e) {

        // في حال تعذّر الوصول لـ localStorage (نادر)
        // نسمح بعرض الصفحة بدل تعطيل التطبيق بالكامل
        console.error("Auth guard error:", e);

    }

})();
